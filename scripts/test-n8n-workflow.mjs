import fs from "node:fs";
import assert from "node:assert/strict";
const w=JSON.parse(fs.readFileSync(new URL("../integrations/n8n/contract-whatsapp.json",import.meta.url),"utf8"));
const byId=Object.fromEntries(w.nodes.map(n=>[n.id,n]));
const validate=new Function("$json",byId["ennour-validate"].parameters.jsCode);
const ack=new Function("$json",byId["ennour-ack"].parameters.jsCode);
const config={phoneNumberId:"123456789",graphVersion:"v24.0",templateName:"ennour_contract",templateLanguage:"fr"};
const body={eventType:"rental.approved",eventId:"ennour-contract-ATL-QA",reference:"ATL-QA",consent:true,to:"212600000000",contractUrl:"https://example.test/api/contracts/shared/test-token"};
assert.equal(validate({...config,body})[0].json.to,body.to);
assert.throws(()=>validate({...config,body:{...body,consent:false}}));
assert.throws(()=>validate({...config,body:{...body,to:"0600000000"}}));
assert.throws(()=>validate({...config,body:{...body,contractUrl:"http://localhost/private"}}));
assert.throws(()=>validate({...config,phoneNumberId:"A_RENSEIGNER",body}));
assert.throws(()=>ack({messages:[]}));
assert.equal(ack({messages:[{id:"wamid.QA"}]})[0].json.status,"accepted");
const chain=["ennour-webhook","ennour-config","ennour-validate","ennour-meta","ennour-ack","ennour-response"];
for(let i=0;i<chain.length-1;i++) assert.equal(w.connections[byId[chain[i]].name].main[0][0].node,byId[chain[i+1]].name);
assert.equal(byId["ennour-webhook"].parameters.authentication,"headerAuth");
assert.equal(w.active,false);
console.log("PASS n8n workflow: authenticated webhook, complete chain, configuration, consent, phone, confidential link and Meta acknowledgement");
